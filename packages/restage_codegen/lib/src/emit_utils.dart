/// The `{{name}}` a conventional `<sourceDir>/{{name}}.<ext>` input binds:
/// its path below [sourceDir], without the extension.
String conventionalOutputStem(String inputPath, String sourceDir) =>
    p.posix.withoutExtension(p.posix.relative(inputPath, from: sourceDir));

final Map<Version, DartFormatter> _formatters = {};

/// Formats [source] as `dart format` does for code at [languageVersion], so
/// the consumer's own `dart format` leaves it unchanged. Without a version it
/// uses the short style.
String formatGeneratedDart(String source, {Version? languageVersion}) {
  final version =
      languageVersion ?? DartFormatter.latestShortStyleLanguageVersion;
  return _formatters
      .putIfAbsent(version, () => DartFormatter(languageVersion: version))
      .format(source);
}

/// The language version `dart format` applies to the build step's package.
Future<Version?> packageLanguageVersion(BuildStep buildStep) async {
  final language = (await buildStep.packageConfig)[buildStep.inputId.package]
      ?.languageVersion;
  return language == null ? null : Version(language.major, language.minor, 0);
}

/// The language version of [library], which its parts share.
Version libraryLanguageVersion(LibraryElement library) =>
    library.languageVersion.effective;

/// Renders [value] as a single-quoted Dart string literal.
///
/// Generated source paths, diagnostics, and reconstructed constants share
/// this renderer so `$` can never become interpolation and control characters
/// cannot break the generated library.
String dartStringLiteral(String value) {
  final buffer = StringBuffer("'");
  for (final rune in value.runes) {
    switch (rune) {
      case 0x08:
        buffer.write(r'\b');
      case 0x09:
        buffer.write(r'\t');
      case 0x0A:
        buffer.write(r'\n');
      case 0x0C:
        buffer.write(r'\f');
      case 0x0D:
        buffer.write(r'\r');
      case 0x24:
        buffer.write(r'\$');
      case 0x27:
        buffer.write(r"\'");
      case 0x5C:
        buffer.write(r'\\');
      default:
        // Lone surrogates stay escaped so the file still encodes as UTF-8.
        if (rune < 0x20 || rune == 0x7F || (rune >= 0xD800 && rune <= 0xDFFF)) {
          buffer
            ..write(r'\u')
            ..write(rune.toRadixString(16).padLeft(4, '0'));
        } else {
          buffer.writeCharCode(rune);
        }
    }
  }
  buffer.write("'");
  return buffer.toString();
}

/// Writes the standard generated-file banner: a `// GENERATED CODE`
/// marker followed by attribution to `restage_codegen`. Callers append
/// any per-emitter comment block, then the imports / declarations.
void writeGeneratedHeader(StringBuffer buf) {
  buf
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln('// Generated by restage_codegen.');
}

/// Appends a stable, machine-readable report of constructor inputs omitted by
/// an emit target.
///
/// The report lives in the generated Dart artifact because A2UI and Widgetbook
/// do not otherwise carry the shared catalog's [PropertyExclusion] sidecar.
/// Empty reports emit nothing, preserving existing generated output byte-for-
/// byte when every constructor input is represented.
void writePropertyExclusionReport(
  StringBuffer buf,
  Iterable<PropertyExclusion> exclusions, {
  String symbolName = r'$RestageExclusions',
}) {
  final sorted = exclusions.toList()
    ..sort((left, right) {
      for (final comparison in [
        left.target.compareTo(right.target),
        left.widget.compareTo(right.widget),
        left.property.compareTo(right.property),
        left.location.compareTo(right.location),
        left.reason.compareTo(right.reason),
      ]) {
        if (comparison != 0) return comparison;
      }
      return 0;
    });
  if (sorted.isEmpty) return;

  buf
    ..writeln()
    ..writeln(
      'const List<Map<String, String>> $symbolName = [',
    );
  for (final exclusion in sorted) {
    buf
      ..writeln('  {')
      ..writeln("    'widget': ${dartStringLiteral(exclusion.widget)},")
      ..writeln("    'property': ${dartStringLiteral(exclusion.property)},")
      ..writeln("    'target': ${dartStringLiteral(exclusion.target)},")
      ..writeln("    'reason': ${dartStringLiteral(exclusion.reason)},")
      ..writeln("    'location': ${dartStringLiteral(exclusion.location)},")
      ..writeln('  },');
  }
  buf.writeln('];');
}

/// Appends `.0` to a bare integer-literal string so it decodes through rfw's
/// `source.v<double>(...)` strict cast. Handles a leading minus sign; passes
/// through anything that already contains a decimal point or doesn't parse
/// as an integer (data refs, expressions, sentinels). Without this coercion,
/// an author-written `int` literal flowing into a length-typed slot is
/// silently nulled at decode time and the slot falls back to whatever
/// default the decoder supplies — dropping the author's explicit value.
String asDoubleLiteral(String literal) {
  if (literal.contains('.')) return literal;
  final body = literal.startsWith('-') ? literal.substring(1) : literal;
  if (body.isEmpty || int.tryParse(body) == null) return literal;
  return '$literal.0';
}
