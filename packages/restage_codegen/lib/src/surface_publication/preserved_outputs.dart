// A step whose build fails writes back the files it wrote last time. They stay
// on disk until the build ends, when the build system replaces its outputs.

import 'dart:io';
import 'dart:isolate';

import 'package:build/build.dart';
import 'package:path/path.dart' as p;
import 'package:restage_codegen/src/surface_publication/output_location.dart';

/// Reads a package's previously generated outputs, keyed by package-relative
/// path.
typedef PriorGeneratedOutputReader =
    Future<Map<String, List<int>>> Function(
      String package,
      RestageOutputLocationPlan plan,
    );

/// A reader that finds no previous outputs.
Future<Map<String, List<int>>> noPriorGeneratedOutputs(
  String package,
  RestageOutputLocationPlan plan,
) async => const {};

/// The prior outputs and refusals of this build, shared by every builder in it.
final Resource<RestagePreservedOutputs> restagePreservedOutputsResource =
    Resource<RestagePreservedOutputs>(RestagePreservedOutputs.new);

/// The generated bytes a failed build must leave unchanged.
final class RestagePreservedOutputs {
  final Map<String, Future<Map<String, List<int>>>> _byPackage = {};
  final Map<String, List<String>> _refusals = {};
  final Set<String> _compiled = {};

  /// Records that this build compiles [package]'s surfaces.
  void compiling(String package) => _compiled.add(package);

  /// Whether this build compiled [package]'s surfaces.
  bool compiledIn(String package) => _compiled.contains(package);

  /// Records why this build refused to compile [package]'s surfaces.
  void refuse(String package, List<String> errors) =>
      _refusals[package] = errors;

  /// Why this build refused to compile [package]'s surfaces, if it did.
  List<String>? refusalOf(String package) => _refusals[package];

  /// The bytes [package] carried before this build, read once per build.
  Future<Map<String, List<int>>> priorOutputsOf(
    String package,
    Future<Map<String, List<int>>> Function() read,
  ) => _byPackage.putIfAbsent(package, read);
}

/// The bytes [path] held before this build, or `null` when it held none.
Future<List<int>?> priorOutputBytes(
  BuildStep buildStep,
  RestageOutputLocationPlan plan,
  PriorGeneratedOutputReader reader,
  String path,
) async {
  final package = buildStep.inputId.package;
  final preserved = await buildStep.fetchResource(
    restagePreservedOutputsResource,
  );
  final prior = await preserved.priorOutputsOf(
    package,
    () => reader(package, plan),
  );
  return prior[path];
}

/// Writes the bytes [path] held before this build back, when it held any.
Future<void> restorePreservedOutput(
  BuildStep buildStep,
  RestageOutputLocationPlan plan,
  PriorGeneratedOutputReader reader,
  String path,
) async {
  final bytes = await priorOutputBytes(buildStep, plan, reader, path);
  if (bytes == null) return;
  await buildStep.writeAsBytes(
    AssetId(buildStep.inputId.package, path),
    bytes,
  );
}

/// Suffixes of the per-library generated files, across every output location.
const List<String> _kPreservedSuffixes = <String>[
  '.restage.g.dart',
  '.rsbundle',
  '.restage.md',
];

/// Reads the package's previously generated outputs from its own directory.
Future<Map<String, List<int>>> readPriorGeneratedOutputs(
  String package,
  RestageOutputLocationPlan plan,
) async {
  final packageLib = await Isolate.resolvePackageUri(
    Uri.parse('package:$package/'),
  );
  if (packageLib == null || packageLib.scheme != 'file') return const {};
  final root = Directory.fromUri(packageLib.resolve('../'));
  return readPriorGeneratedOutputsFromDirectory(root, plan);
}

/// Captures the previous valid files under the selected package directory.
Map<String, List<int>> readPriorGeneratedOutputsFromDirectory(
  Directory root,
  RestageOutputLocationPlan plan,
) {
  if (!root.existsSync()) return const {};
  final outputs = <String, List<int>>{};
  for (final path in <String>[
    plan.publicationManifestPath,
    plan.outputIndexPath,
    plan.measurementOutputIndexPath,
    plan.analyticsIdMetadataPath,
    plan.capturePlanPath,
    plan.customCatalogPath,
    plan.buildResultPath,
  ]) {
    final file = File(p.join(root.path, path));
    if (file.existsSync()) outputs[path] = file.readAsBytesSync();
  }
  _collectGeneratedFiles(root, root: root.path, outputs: outputs);
  final portable = Directory(p.join(root.path, plan.outputRoot!));
  if (portable.existsSync()) {
    _collectGeneratedFiles(
      portable,
      root: root.path,
      outputs: outputs,
      includeHidden: true,
    );
  }
  return outputs;
}

void _collectGeneratedFiles(
  Directory directory, {
  required String root,
  required Map<String, List<int>> outputs,
  bool includeHidden = false,
}) {
  for (final entity in directory.listSync(followLinks: false)) {
    final name = p.basename(entity.path);
    if (!includeHidden && (name.startsWith('.') || name == 'build')) continue;
    if (entity is Directory) {
      _collectGeneratedFiles(
        entity,
        root: root,
        outputs: outputs,
        includeHidden: includeHidden,
      );
      continue;
    }
    if (entity is! File) continue;
    if (!_kPreservedSuffixes.any(name.endsWith)) continue;
    final relative = p.posix.joinAll(
      p.split(p.relative(entity.path, from: root)),
    );
    outputs[relative] = entity.readAsBytesSync();
  }
}
