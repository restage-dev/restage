import 'package:analyzer/dart/element/element.dart';
import 'package:analyzer/dart/element/type.dart';
import 'package:build/build.dart';
import 'package:restage_codegen/src/emit_utils.dart';
import 'package:restage_codegen/src/surface_publication/compiler_handoff.dart';
import 'package:restage_shared/restage_shared.dart';

/// The generated list of every surface reference a package compiles.
const String kRestageSurfaceListPath = 'lib/restage_surfaces.g.dart';

const String _kSurfaceRefName = 'RestageSurfaceRef';
const String _kGeneratedPartSuffix = '.restage.g.dart';

/// Writes `lib/restage_surfaces.g.dart`: `restageSurfaces`, every generated
/// surface reference and every compiled paywall, for
/// `Restage.configure(surfaces:)`.
final class RestageSurfaceListBuilder implements Builder {
  const RestageSurfaceListBuilder();

  @override
  Map<String, List<String>> get buildExtensions => const {
        r'$lib$': ['restage_surfaces.g.dart'],
      };

  @override
  Future<void> build(BuildStep buildStep) async {
    final bundle = await readRestageCompilerHandoff(buildStep);
    final manifest = bundle?.manifest;
    if (bundle == null || manifest == null) return;
    if (manifest.publications.isEmpty) return;
    final package = buildStep.inputId.package;

    final paywallIds = <String>{
      for (final entry in manifest.publications)
        if (entry.publication.surface == Surface.paywall)
          entry.publication.slug,
    }.toList()
      ..sort();

    final libraryPaths = <String>{
      for (final entry in manifest.publications) ...entry.sources,
      ...bundle.artifactLibraryPaths.values,
    }.where((path) => path.startsWith('lib/')).toList()
      ..sort();

    final refs = <SurfaceListReference>[];
    for (final path in libraryPaths) {
      final id = AssetId(package, path);
      if (!await buildStep.resolver.isLibrary(id)) continue;
      final library = await buildStep.resolver.libraryFor(id);
      for (final name in generatedSurfaceRefNames(library)) {
        refs.add(SurfaceListReference(libraryPath: path, name: name));
      }
    }

    await buildStep.writeAsString(
      AssetId(package, kRestageSurfaceListPath),
      formatGeneratedDart(
        emitRestageSurfaceList(
          package: package,
          paywallIds: paywallIds,
          refs: refs,
        ),
        languageVersion: await packageLanguageVersion(buildStep),
      ),
    );
  }
}

/// One generated reference, named [name], declared by the library at
/// [libraryPath].
final class SurfaceListReference {
  const SurfaceListReference({required this.libraryPath, required this.name});

  final String libraryPath;
  final String name;
}

/// The public top-level references [library]'s generated part declares whose
/// type is a Restage surface reference, sorted by name.
List<String> generatedSurfaceRefNames(LibraryElement library) {
  final names = <String>[
    for (final variable in library.topLevelVariables)
      if (variable.name case final name?
          when !name.startsWith('_') &&
              variable.firstFragment.libraryFragment.source.uri.path
                  .endsWith(_kGeneratedPartSuffix) &&
              _isSurfaceRef(variable.type))
        name,
  ]..sort();
  return names;
}

bool _isSurfaceRef(DartType type) {
  if (type is! InterfaceType) return false;
  for (final candidate in <InterfaceType>[type, ...type.allSupertypes]) {
    final element = candidate.element;
    if (element.name == _kSurfaceRefName &&
        element.library.identifier.startsWith('package:restage/')) {
      return true;
    }
  }
  return false;
}

/// The Dart source of `restage_surfaces.g.dart`.
String emitRestageSurfaceList({
  required String package,
  required List<String> paywallIds,
  required List<SurfaceListReference> refs,
}) {
  final libraries = <String>{for (final ref in refs) ref.libraryPath}.toList()
    ..sort();
  final prefixes = <String, String>{
    for (var index = 0; index < libraries.length; index += 1)
      libraries[index]: 's$index',
  };
  final buffer = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln('// Generated by restage_codegen.')
    ..writeln()
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln("import 'package:restage/restage.dart' as restage;");
  for (final library in libraries) {
    final uri = 'package:$package/${library.substring('lib/'.length)}';
    buffer.writeln('import ${dartStringLiteral(uri)} as ${prefixes[library]};');
  }
  buffer
    ..writeln()
    ..writeln('/// Every surface this package compiles, for')
    ..writeln('/// `Restage.configure(surfaces: restageSurfaces)`.')
    ..writeln('final List<restage.RestageSurfaceRef> restageSurfaces =')
    ..writeln('    List<restage.RestageSurfaceRef>.unmodifiable(')
    ..writeln('  <restage.RestageSurfaceRef>[');
  for (final id in paywallIds) {
    buffer.writeln('    const restage.PaywallRef(${dartStringLiteral(id)}),');
  }
  final sorted = [...refs]..sort((left, right) {
      final library = left.libraryPath.compareTo(right.libraryPath);
      return library != 0 ? library : left.name.compareTo(right.name);
    });
  for (final ref in sorted) {
    buffer.writeln('    ${prefixes[ref.libraryPath]}.${ref.name},');
  }
  buffer
    ..writeln('  ],')
    ..writeln(');');
  return buffer.toString();
}
