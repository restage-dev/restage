import 'dart:convert';
import 'dart:io';

import 'package:analyzer/dart/analysis/analysis_context_collection.dart';
import 'package:analyzer/dart/analysis/results.dart';
import 'package:restage_codegen/src/a2ui/a2ui_catalog_adapter.dart';
import 'package:restage_codegen/src/a2ui/a2ui_dart_emitter.dart';
import 'package:restage_codegen/src/a2ui/a2ui_seam_assembly.dart';
import 'package:restage_codegen/src/emit_utils.dart';
import 'package:rfw_catalog_schema/rfw_catalog_schema.dart';
import 'package:test/test.dart';

import '../helpers.dart';

void main() {
  test(
    'namespace and rich-child fixture is generated by the production emitter',
    () async {
      const base = '../restage_a2ui/test/generated/envelope_collision';
      final path = File(
        '${base}_fixture.dart',
      ).absolute.resolveSymbolicLinksSync();
      final collection = AnalysisContextCollection(includedPaths: [path]);
      addTearDown(collection.dispose);
      final result =
          await collection
                  .contextFor(path)
                  .currentSession
                  .getResolvedLibrary(path)
              as ResolvedLibraryResult;
      final uri = result.element.uri.toString();
      const library = WidgetLibrary.custom('namespace.proof');
      final widgets = [
        entry(
          name: 'CustomCard',
          library: library,
          flutterType: '$uri#PropsNamespaceProbe',
          properties: [
            for (final name in [
              'id',
              'component',
              'catalogId',
              'props',
              'literalValue',
              'pathValue',
              'callValue',
            ])
              prop(name, PropertyType.string, required: true),
            for (final name in ['node', 'counts', 'meta'])
              prop(name, PropertyType.structured, required: true),
            prop(
              'leading',
              PropertyType.widget,
              required: true,
              description: 'Content shown before the rich details.',
            ),
            prop('children', PropertyType.widgetList, required: true),
            prop('enabled', PropertyType.boolean, required: true),
            prop('onAction', PropertyType.event, required: true),
            prop('onEnabledChanged', PropertyType.event, required: true),
          ],
        ),
        entry(
          name: 'InlineCard',
          library: library,
          flutterType: '$uri#PropsNamespaceChild',
          properties: [
            prop(
              'child',
              PropertyType.widget,
              required: true,
              description: 'Content shown in the header.',
            ),
          ],
        ),
        entry(
          name: 'Leaf',
          library: library,
          flutterType: '$uri#PropsNamespaceLeaf',
          properties: [prop('label', PropertyType.string, required: true)],
        ),
      ];
      widgets.add(
        entry(
          name: 'OtherCard',
          library: library,
          flutterType: '$uri#PropsNamespaceProbe',
          properties: widgets.first.properties,
        ),
      );
      final seams = assembleA2uiSeams([
        for (final widget in widgets)
          (
            entry: widget,
            element: result.element.classes.firstWhere(
              (c) => c.name == widget.flutterType.split('#').last,
            ),
          ),
      ]);
      expect(seams.issues, isEmpty);
      final catalog = Catalog(
        schemaVersion: kSupportedSchemaVersion,
        generatedAt: '1970-01-01T00:00:00Z',
        libraries: {
          library: const LibraryInfo(version: '1.0.0', capabilityVersion: 1),
        },
        widgets: widgets,
      );
      final registration = emitA2uiCatalog(
        catalog,
        richShapes: seams.richShapes,
        eventSeam: seams.eventSeam,
        pairingSeam: seams.pairingSeam,
      );
      for (final name in ['CustomCard', 'OtherCard']) {
        final schema = registration.components
            .singleWhere((c) => c.name == name)
            .dataSchema;
        expect(schema[r'$defs'], contains('CollisionNode'));
        expect(
          jsonEncode(schema),
          contains('#/\$defs/restage_component_$name/\$defs/CollisionNode'),
        );
        final other = name == 'CustomCard' ? 'OtherCard' : 'CustomCard';
        expect(
          jsonEncode(schema),
          isNot(contains('#/\$defs/restage_component_$other/')),
        );
      }
      final inline = registration.components
          .singleWhere((c) => c.name == 'InlineCard')
          .dataSchema;
      expect(
        ((inline['properties']! as Map)['props_child']! as Map)['description'],
        'Content shown in the header.',
      );
      final rich = registration.components
          .singleWhere((c) => c.name == 'CustomCard')
          .dataSchema;
      final richRoot = (rich[r'$defs']! as Map)['__a2ui_root__']! as Map;
      expect(
        ((richRoot['properties']! as Map)['props_leading']!
            as Map)['description'],
        'Content shown before the rich details.',
      );
      final source = emitA2uiCatalogDart(
        catalog,
        registration: registration,
        richShapes: seams.richShapes,
        eventSeam: seams.eventSeam,
        pairingSeam: seams.pairingSeam,
      );
      final fixtureSource = source.replaceAll(
        uri,
        'envelope_collision_fixture.dart',
      );
      final document = const JsonEncoder.withIndent(
        '  ',
      ).convert(registration.toJson());
      expect(document, isNot(contains('commonTypesRef')));
      expect(document, contains('id => props_id'));
      expect(document, contains('props => props_props'));
      expect(document, contains(r'common_types.json#/$defs/ComponentId'));
      final artifacts = {
        '${base}_catalog.g.dart':
            '${formatGeneratedDart(fixtureSource).trimRight()}\n',
        '${base}_catalog.a2ui.json': '$document\n',
      };
      for (final entry in artifacts.entries) {
        final file = File(entry.key);
        if (Platform.environment['REGEN_A2UI_DART_GOLDEN'] == '1') {
          file.writeAsStringSync(entry.value);
        }
        expect(
          file.readAsStringSync(),
          entry.value,
          reason: 'Regenerate with REGEN_A2UI_DART_GOLDEN=1',
        );
      }
    },
  );
}
