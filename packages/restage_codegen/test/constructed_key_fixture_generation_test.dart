import 'dart:convert';
import 'dart:io';
import 'package:dart_style/dart_style.dart';
import 'package:pub_semver/pub_semver.dart';
import 'package:restage_codegen/src/installed_native_call.dart';
import 'package:restage_codegen/src/factory_emitter.dart';
import 'package:restage_codegen/src/capability_derivation.dart';
import 'package:restage_shared/rfw_formats.dart' as rfw;
import 'package:restage_codegen/src/native_catalog_index.dart';
import 'package:restage_shared/restage_shared.dart';
import 'package:test/test.dart';
import 'constructed_key_authoring_test.dart' show compileConstructedKey;

void main() {
  test('constructed key fixture comes from ordinary resolved widget source', () async {
    final catalog = decodeCatalog(
      File(
        '../restage_core/lib/src/widget_catalog/catalog.json',
      ).readAsStringSync(),
    );
    final out = StringBuffer(
      "// Generated by constructed_key_fixture_generation_test.dart.\nimport 'package:flutter/widgets.dart';\nimport 'package:restage_core/restage_core.dart' as r;\nimport 'package:restage_shared/restage_shared.dart' as s;\n",
    );
    final bodies = <String, String>{
      'Lazy':
          "LayoutBuilder(builder: (context, constraints) { final itemKey = ObjectKey(items[0]); return AnimatedContainer(key:itemKey, duration:Duration(milliseconds:1), width:20, height:20); })",
      'Nested':
          "LayoutBuilder(builder: (context, constraints) { final itemKey = ObjectKey(items[0]); return LayoutBuilder(builder: (context, inner) => AnimatedContainer(key:itemKey, duration:Duration(milliseconds:1), width:20, height:20)); })",
      'Delegate':
          "GridView.custom(gridDelegate:SliverGridDelegateWithFixedCrossAxisCount(crossAxisCount:1), childrenDelegate:SliverChildBuilderDelegate((context,index) { final itemKey=ObjectKey(items[index]); return AnimatedContainer(key:itemKey,duration:Duration(milliseconds:1),width:20,height:20); },childCount:count,findChildIndexCallback:(Key key) => findIndex(key)))",
      'Builder':
          "GridView.builder(gridDelegate:SliverGridDelegateWithFixedCrossAxisCount(crossAxisCount:1), itemBuilder:(context,index) { final itemKey=ObjectKey(items[index]); return AnimatedContainer(key:itemKey,duration:Duration(milliseconds:1),width:20,height:20); },itemCount:count,findChildIndexCallback:(Key key) => findIndex(key))",
      'Skipped':
          "LayoutBuilder(builder: (context, constraints) { if (constraints.maxWidth < 0) { final itemKey = ObjectKey(items[0]); return Text('item', key:itemKey); } return const SizedBox(); })",
    };
    bodies['NestedDelegate'] =
        "LayoutBuilder(builder:(context,constraints)=>${bodies['Delegate']})";
    String item(String key) =>
        'AnimatedContainer(key:$key,duration:Duration(milliseconds:1),width:20,height:20)';
    for (final kind in ['Inline', 'Named']) {
      final first = item(
        kind == 'Inline' ? "const ObjectKey('first')" : 'P.stableKey',
      );
      final second = item(
        kind == 'Inline' ? "const ObjectKey('second')" : 'P.otherKey',
      );
      bodies['Constant$kind'] =
          'Row(children:count==2 ? [$first,$second] : [$second,$first])';
    }
    bodies['ConstantAlias'] = 'Row(children:[...children])';
    out.writeln(
      "class P { static const stableKey=ObjectKey('first'); static const otherKey=ObjectKey('second'); }",
    );
    for (final entry in bodies.entries) {
      final result = await compileConstructedKey(
        entry.value,
        prelude: entry.key == 'ConstantAlias'
            ? "const firstKey=P.stableKey; const secondKey=ObjectKey('second'); final first=${item('firstKey')}; final second=${item('secondKey')}; final children=count==2 ? [first,second] : [second,first];"
            : '',
      );
      expect(
        result.issues,
        isEmpty,
        reason: result.issues.map((i) => i.message).join('\n'),
      );
      final manifest = deriveCapabilityManifest(
        rfw.parseLibraryFile(
          'import restage.core; widget Root = ${result.dsl};',
        ),
        catalog,
        hoisted: result.hoisted,
      );
      expect(
        manifest.issues,
        isEmpty,
        reason: manifest.issues.map((i) => i.message).join('\n'),
      );
      expect(manifest.manifest!.builtInFloor, 24);
      out.writeln(
        "const constructed${entry.key}Source = ${jsonEncode('import restage.core; widget Root = ${result.dsl};')};",
      );
      out.writeln(
        '({Map<String,r.NativeBinding<Object?>> bindings, Map<String,Object?> context}) constructed${entry.key}Mount(List<Object> items, [int? Function(Key)? findIndex, int count = 2]) {',
      );
      out.writeln(
        'final bindings = <String,r.NativeBinding<Object?>>{}; final context = <String,Object?>{"count":2};',
      );
      for (final h in result.hoisted) {
        final contract = h.nativeContract;
        if (contract == null) {
          out.writeln(
            'context[${jsonEncode(h.key)}] = ${h.mountSource((name) => name == 'findIndex' ? 'findIndex!' : name)};',
          );
          continue;
        }
        final value =
            h.nativeCall?.adapterSource(core: 'r.', shared: 's.') ??
            h.mountSource((name) => name == 'findIndex' ? 'findIndex!' : name);
        out.writeln(
          'bindings[${jsonEncode(h.key)}] = r.NativeBinding(contract:${nativeContractSource(contract, 's.')},value:$value);',
        );
        out.writeln(
          'context[${jsonEncode(h.key)}] = ${nativeContractSource(contract, 's.')}.reference(${jsonEncode(h.key)});',
        );
      }
      out.writeln('return (bindings:bindings,context:context); }');
    }

    final factories = StringBuffer(
      "// Generated by constructed_key_fixture_generation_test.dart.\nimport 'package:flutter/material.dart';\nimport 'package:flutter/gestures.dart';\nimport 'package:restage_core/restage_core.dart';\nimport 'package:restage_shared/restage_shared.dart';\nimport 'package:rfw/rfw.dart';\n",
    );
    for (final name in [
      'AnimatedContainer',
      'LayoutBuilder',
      'SizedBox',
      'Text',
      'GridViewCustom',
      'GridViewBuilder',
      'Row',
    ]) {
      factories.writeln(
        emitFactoryFunction(
          catalog.widgets.singleWhere((w) => w.name == name),
          nativeIndex: NativeCatalogIndex(catalog),
          publicName: true,
        )!,
      );
    }
    final factoryText = DartFormatter(
      languageVersion: Version(3, 5, 0),
    ).format(factories.toString());
    final factoryFile = File(
      '../restage_core/test/fixtures/constructed_key_factories.g.dart',
    );
    if (Platform.environment['WRITE_CONSTRUCTED_KEY_FIXTURE'] == '1')
      factoryFile.writeAsStringSync(factoryText);
    expect(factoryFile.readAsStringSync(), factoryText);
    final generated = DartFormatter(
      languageVersion: Version(3, 5, 0),
    ).format(out.toString());
    final file = File(
      '../restage_core/test/fixtures/constructed_key_source.g.dart',
    );
    if (Platform.environment['WRITE_CONSTRUCTED_KEY_FIXTURE'] == '1')
      file.writeAsStringSync(generated);
    expect(file.readAsStringSync(), generated);
  });
}
